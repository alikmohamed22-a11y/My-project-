# words -> web/cl_words.js (frame of each word start/end @30 fps). Usage: python3 tools/mkwords.py work/words.json   (or --estimate)
import json, sys, re
SCRIPT = open('/root/shorts/clip1/work/script_tts.txt').read().split()
if sys.argv[1] == '--estimate':
    W, t = [], 0.15
    for w in SCRIPT:
        d = 0.21 + 0.045 * len(re.sub(r'\W', '', w)); W.append({'w': w, 's': round(t, 3), 'e': round(t + d, 3)}); t += d + (0.32 if w[-1] in '.!?' else 0.12 if w[-1] in ',' else 0.02)
    json.dump(W, open('/root/shorts/clip1/work/words_est.json', 'w'), indent=0)
else:
    W = json.load(open(sys.argv[1]))
import os, math, wave
VW = '/root/shorts/clip1/audio/voice.wav'
nf = int(math.ceil(wave.open(VW).getnframes() / 48000 * 30)) if os.path.exists(VW) and sys.argv[1] != '--estimate' else int((W[-1]['e'] + 1.3) * 30) + 1
out = 'export const WORDS = ' + json.dumps([[round(w['s'] * 30), round(w['e'] * 30), re.sub(r"[^a-z0-9']", '', w['w'].lower())] for w in W]) + ';\nexport const NF_VOICE = %d;\n' % nf
open('/root/shorts/clip1/web/cl_words.js', 'w').write('// [CL-story] word frames (generated by tools/mkwords.py)\n' + out)
print(len(W), 'words, NF', nf)
