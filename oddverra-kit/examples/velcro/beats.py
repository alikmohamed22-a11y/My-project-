# work/words.json -> web/vc_beats.js : frame of each anchor word (start frame, 30 fps), shot starts and NF
import json, re, math
W = json.load(open('words.json'))
norm = lambda s: re.sub(r"[^a-z0-9']", '', s.lower())
def at(word, k=0, end=False):
    hits = [w for w in W if norm(w['w']) == word]
    if len(hits) <= k: raise SystemExit(f'missing anchor {word} #{k}: ' + ' '.join(norm(w["w"]) for w in W))
    return int(round((hits[k]['e'] if end else hits[k]['s']) * 30))
A = {  # key: (word, occurrence)
  'velcro': ('velcro', 0), 'dog': ('dog', 0), 'covered': ('covered', 0), 'burrs': ('burrs', 0),
  'in41': ('in', 1), 'nineteen': ('nineteen', 0), 'swiss': ('swiss', 0), 'george': ('george', 0), 'home': ('home', 0), 'hunting': ('hunting', 0), 'his': ('his', 0), 'full': ('full', 0),
  'most': ('most', 0), 'pick': ('pick', 0), 'george2': ('george', 1), 'under': ('under', 0), 'microscope': ('microscope', 0),
  'yousee': ('you', 0), 'every': ('every', 0), 'tiny': ('tiny', 0), 'hooks': ('hooks', 0), 'and': ('and', 1), 'grab': ('grab', 0), 'loop': ('loop', 0), 'fur': ('fur', 0), 'fabric': ('fabric', 0),
  'so': ('so', 0), 'idea': ('idea', 0), 'fake': ('fake', 0), 'hooks3': ('hooks', 2), 'loops': ('loops', 0),
  'but': ('but', 0), 'nightmare': ('nightmare', 0), 'cotton': ('cotton', 0), 'wore': ('wore', 0), 'fast': ('fast', 0),
  'nylon': ('nylon', 0), 'reportedly': ('reportedly', 0), 'infrared': ('infrared', 0), 'then': ('then', 0), 'cut': ('cut', 0), 'right': ('right', 0),
  'took': ('took', 0), 'decade': ('decade', 0),
  'named': ('named', 0), 'french': ('french', 0), 'velours': ('velours', 0), 'velvet': ('velvet', 0), 'crochet': ('crochet', 0), 'hook': ('hook', 0), 'velcro2': ('velcro', 1),
  'patented': ('patented', 0), 'fifties': ('midfifties', 0), 'but2': ('but', 1), 'fashion': ('fashion', 0), 'nose': ('nose', 0), 'looked': ('looked', 0), 'cheap': ('cheap', 0),
  'then2': ('then', 1), 'nasa': ('nasa', 0), 'apollo': ('apollo', 0), 'tools': ('tools', 0), 'snacks': ('snacks', 0), 'floating': ('floating', 0), 'away': ('away', 0),
  'so3': ('so', 1), 'sound': ('sound', 0), 'thank': ('thank', 0), 'dog3': ('dog', 2), 'stay': ('stay', 0), 'weeds': ('weeds', 0),
}
B = {k: at(*v) for k, v in A.items()}
B['endFull'] = at('them', 0, True); B['endMicro'] = at('microscope', 0, True); B['endFabric'] = at('fabric', 0, True); B['endWeeds'] = at('weeds', 0, True)
NF = int(math.ceil((W[-1]['e'] + 1.3) * 30))
open('../web/vc_beats.js', 'w').write('// generated by work/beats.py from work/words.json (frame of each anchor word at 30 fps)\nexport const B = ' + json.dumps(B) + ';\nexport const NF = ' + str(NF) + ';\n')
print('NF', NF, B)
