# words.json -> ../web/mm_words.js (word, start frame, end frame) for the story timeline
import json, re
W = json.load(open('words.json'))
rows = [[re.sub(r"[^\w'-]", '', w['w']).lower(), int(round(w['s'] * 30)), int(round(w['e'] * 30))] for w in W]
open('../web/mm_words.js', 'w').write('// [MM-story] generated by work/mkwords.py from work/words.json: [word, start frame, end frame]\nexport const WORDS = ' + json.dumps(rows) + ';\n')
print(len(rows), 'words, last end frame', rows[-1][2])
